/** The technical renames as one function: used to tell an intended string change from an unintended one */
export function applyTechnicalMap(text) {
  return text
    .replace(/@genoffice\//g, '@seuoffice/')
    .replace(/GENOFFICE|IEUMOFFICE/g, 'SEUOFFICE')
    .replace(/Genoffice|Ieumoffice/g, 'Seuoffice')
    .replace(/genoffice|ieumoffice/g, 'seuoffice')
}

