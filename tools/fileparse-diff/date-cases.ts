export const SPECS: Spec[] = [
  {
    fn: 'builtinDateFormat',
    extensions: [],
    mutateText: true,
    call: ({ text = '' }) => builtinDateFormat(Number(text)),
    built: () => Array.from({ length: 70 }, (_, n) => ({ label: `builtin ${n}`, text: String(n) })),
  },
  {
    fn: 'classifyFormatCode',
    extensions: [],
    mutateText: true,
    call: ({ text = '' }) => classifyFormatCode(text),
    built: () => formats.map((text) => ({ label: `format ${text}`, text })),
  },
  {
    fn: 'formatSerial',
    extensions: [],
    mutation: 'none',
    call: ({ text = '', args = {} }) =>
      formatSerial(Number(text), args.parts as DateFormatParts, Boolean(args.date1904)),
    built: () =>
      parts.flatMap((parts, i) =>
        serials.flatMap((serial) =>
          [false, true].map((date1904) => ({
            label: `serial ${serial} parts ${i} 1904=${date1904}`,
            text: String(serial),
            args: { parts, date1904 },
          })),
        ),
      ),
  },
]
