const esc = (s: string): string =>
  [...s]
    .map((ch) => {
      const c = ch.codePointAt(0)!
      return ch === '"'
        ? '\\"'
        : ch === '\\'
          ? '\\\\'
          : ch === '\n'
            ? '\\n'
            : ch === '\r'
              ? '\\r'
              : ch === '\t'
                ? '\\t'
                : c >= 0x20 && c < 0x7f
                  ? ch
                  : `\\u{${c.toString(16)}}`
    })
    .join('')
