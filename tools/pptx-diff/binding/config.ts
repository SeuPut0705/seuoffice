// The pptx engine's side of the binding generator's config
// (tools/docx-diff/binding/config.ts).
import type { EngineConfig } from '../../docx-diff/binding/config'
import { MODEL_TYPES, decodable, wireParams } from './kinds'
import { PPTX_APPEND, PPTX_HAND_ROUTES, PPTX_REPLACE, type PptxOverride, isHandRoute, overrideOf } from './overrides'
import { pptxRow } from './rows'
import { pptxWrapperBody } from './wrapper'

/** the Rust file that is the port of a TypeScript module: index.ts is `deck`, the rest are named alike */
const RUST_MODULE: Readonly<Record<string, string>> = {
  index: 'deck',
  'xml-parser': 'xml_utils',
  'own-value': 'own_value',
}

/** the helpers of engine.ts the wrappers call */
const ENGINE_NAMES = ['call', 'slideIndex', 'forgetSnapshot', 'shared']

export const pptx: EngineConfig = {
  name: 'pptx',
  packageDir: 'packages/pptx-engine',
  packageName: '@seuoffice/pptx-engine',
  reference: 'tools/pptx-diff/reference',
  bindingDir: 'tools/pptx-diff/binding',
  manifest: 'tools/pptx-diff/binding/manifest.json',
  table: { file: 'crates/office-wasm/src/invoke/pptx_table.rs', module: 'pptx_table', routes: 'pptx_routes' },
  crates: [{ dir: 'crates/pptx-engine/src', crate: 'pptx_engine' }],
  plumbing: ['engine', 'engine-adopt'],
  shapesModule: false,
  typeShapes: MODEL_TYPES,
  dropUnused: true,
  dropReexportRefs: true,
  pluginModule: (module) =>
    module === 'index' || module.startsWith('node/') || module.startsWith('engine-') || module === 'init',
  overrideOf,
  ownRow: (override) => !!(override as PptxOverride | undefined)?.pass,
  isHandRoute,
  handRoutes: PPTX_HAND_ROUTES,
  hostModules: {},
  append: PPTX_APPEND,
  replace: PPTX_REPLACE,
  rustName: (name) =>
    ({ elementCNvPrId: 'element_cnvpr_id', unescapeXml: 'unescape_xml', xmlParser: 'xml_parse_object' })[name],
  rustModule: (module) => `crates/pptx-engine/src/${RUST_MODULE[module] ?? module.replaceAll('-', '_')}.rs`,
  decodable,
  wireParams,
  wrapperBody: pptxWrapperBody,
  coreImports: (wrappers) => {
    const used = ENGINE_NAMES.filter((n) => new RegExp(`\\b${n}\\(`).test(wrappers))
    return [
      ...(used.length ? [`import { ${used.join(', ')} } from './engine'`] : []),
      ...(/\bhand\./.test(wrappers) ? [`import * as hand from './engine-hand'`] : []),
    ]
  },
  row: pptxRow,
  rustHead: `//! GENERATED by tools/docx-diff/binding/gen.ts --engine pptx from tools/pptx-diff/binding/manifest.json.
//! Do not edit: change the manifest's inputs (tools/pptx-diff/binding/overrides.ts) and run the generator.
//!
//! The table \`invoke\` answers a \`pptx.<export>\` by: each row reads the
//! positional JSON arguments by the Rust parameter kinds (\`pptx.rs\`), fills
//! the ones the host owns (uuid, clock, id counter), calls the port and
//! answers \`{ "$result": value, "$out": { "<wire index>": answer } }\`: \`$out\`
//! holds the arguments the port changed, for the binding to write back into
//! the caller's objects.
#![allow(dead_code, unused_variables, unused_mut, clippy::all)]

use serde::Serialize;
use serde::de::DeserializeOwned;
use serde_json::{Value, json};

use super::{InvokeEnv, pptx, pptx_routes};

fn at(args: &[Value], index: usize) -> &Value {
    args.get(index).unwrap_or(&Value::Null)
}

/// A hand row's answer: the value, no argument changed.
fn reply(value: impl Serialize) -> Out {
    Ok(Some(pptx::answer(Some(to_json(&value)?), Vec::new())))
}

`,
  invokePrelude: '    let args = pptx::inline_blobs(env, args)?;\n    let args = &*args;\n',
  rustDocxHelpers: false,
}
