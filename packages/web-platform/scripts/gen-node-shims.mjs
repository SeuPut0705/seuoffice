/**
 * Writes src/shims/<module>.ts for the Node built-ins the web build aliases.
 *
 * Bundlers fail on a named import the target module does not export, so each
 * shim lists every export of the real module. Importing a shim is safe; calling
 * one of its functions throws WebUnsupportedError. Exports with a browser
 * meaning come from src/shims/impl/<module>.ts (IMPL) or are written out in
 * OWN. Re-run after a Node upgrade:
 * `node packages/web-platform/scripts/gen-node-shims.mjs`.
 */
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import * as prettier from 'prettier'

const require = createRequire(import.meta.url)
const shimsDir = fileURLToPath(new URL('../src/shims/', import.meta.url))

/** module id → shim file stem */
const MODULES = {
  zlib: 'zlib',
  crypto: 'crypto',
  fs: 'fs',
  'fs/promises': 'fs-promises',
  os: 'os',
  child_process: 'child-process',
  worker_threads: 'worker-threads',
  readline: 'readline',
  net: 'net',
  'stream/promises': 'stream-promises',
  url: 'url',
  // the AI provider's subscription CLIs and login server, which the web never runs
  string_decoder: 'string-decoder',
  http: 'http',
}

/** exports implemented in src/shims/impl/<stem>.ts */
const IMPL = {
  zlib: [
    'crc32',
    'deflateRawSync',
    'deflateSync',
    'gunzipSync',
    'gzipSync',
    'inflateRawSync',
    'inflateSync',
    'unzipSync',
  ],
  crypto: [
    'createCipheriv',
    'createDecipheriv',
    'createHash',
    'createHmac',
    'getHashes',
    'getRandomValues',
    'randomBytes',
    'randomUUID',
    'subtle',
    'timingSafeEqual',
    'webcrypto',
  ],
  url: ['fileURLToPath', 'pathToFileURL'],
}

/** other exports with a browser meaning: name → TS expression */
const OWN = {
  fs: { promises: 'promisesModule' },
  os: {
    homedir: "(): string => '/web'",
    tmpdir: "(): string => '/web'",
    EOL: "'\\n'",
    devNull: "'/dev/null'",
  },
  worker_threads: {
    isMainThread: 'true',
    isInternalThread: 'false',
    parentPort: 'null',
    workerData: 'null',
    threadId: '0',
    threadName: "'main'",
    resourceLimits: '{}',
    SHARE_ENV: "Symbol('SHARE_ENV')",
    locks: '{}',
  },
  url: { URL: 'globalThis.URL', URLSearchParams: 'globalThis.URLSearchParams' },
}

const PRELUDE = { fs: "import * as promisesModule from './fs-promises'" }

const IDENT = /^[A-Za-z_$][\w$]*$/

for (const [id, stem] of Object.entries(MODULES)) {
  const real = require(id)
  const own = OWN[id] ?? {}
  const impl = new Set(IMPL[id] ?? [])
  const names = Object.keys(real)
    .filter((name) => IDENT.test(name) && name !== 'default')
    .sort()
  const missing = [...impl].filter((name) => !names.includes(name))
  if (missing.length) throw new Error(`${id} has no export ${missing.join(', ')}`)
  const lines = [
    `// Generated by scripts/gen-node-shims.mjs from Node ${process.version}. Do not edit.`,
    "import { nodeStub } from '../stub'",
  ]
  if (impl.size) lines.push(`import * as impl from './impl/${stem}'`)
  if (PRELUDE[id]) lines.push(PRELUDE[id])
  lines.push('')
  for (const name of names) {
    let value
    if (impl.has(name)) value = `impl.${name}`
    else if (name in own) value = own[name]
    else if (typeof real[name] === 'function') value = `nodeStub('${id}.${name}')`
    else if (real[name] !== null && typeof real[name] === 'object')
      value = safeJson(real[name]) ?? '{}'
    else value = JSON.stringify(real[name]) ?? 'undefined'
    lines.push(`export const ${name} = ${value}`)
  }
  lines.push('', `export default { ${names.join(', ')} }`, '')
  const file = `${shimsDir}${stem}.ts`
  const options = { ...(await prettier.resolveConfig(file)), filepath: file }
  writeFileSync(file, await prettier.format(lines.join('\n'), options))
}

function safeJson(value) {
  try {
    return JSON.stringify(value)
  } catch {
    return null
  }
}
