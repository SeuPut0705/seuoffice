fn font_map(font: &str) -> Option<&'static [(u8, &'static str)]> {
    // the table answers for its own keys only (`Object.hasOwn`, `ownValue`)
    match trim(font).to_lowercase().as_str() {
        "symbol" => Some(SYMBOL),
        "wingdings" => Some(WINGDINGS),
        "wingdings 2" => Some(WINGDINGS_2),
        "wingdings 3" => Some(WINGDINGS_3),
        "webdings" => Some(WEBDINGS),
        _ => None,
    }
}

pub fn is_symbol_font(font: Option<&str>) -> bool {
    font.is_some_and(|font| !font.is_empty() && font_map(font).is_some())
}

/// Glyph code (raw byte or its U+F0xx private-use form) to its Unicode
/// equivalent; `None` when unknown.
pub fn decode_symbol_char(font: &str, code: f64) -> Option<&'static str> {
    let map = font_map(font)?;
    let low = if (61440.0..=61695.0).contains(&code) {
        code - 61440.0
    } else {
        code
    };
    if low == 32.0 {
        return Some(" ");
    }
    if low.fract() != 0.0 || !(0.0..=255.0).contains(&low) {
        return None;
    }
    let key = low as u8;
    map.binary_search_by_key(&key, |&(code, _)| code)
        .ok()
        .and_then(|at| map.get(at))
        .map(|&(_, glyph)| glyph)
}

/// The U+F0xx private-use form of a w:sym hex char; `None` for a bad char.
pub fn symbol_pua_char(char_hex: &str) -> Option<String> {
    let code = parse_int(char_hex, Radix::Sixteen);
    if !code.is_finite() {
        return None;
    }
    let pua = ((to_int32(code) & 0xff) + 0xf000) as u32;
    char::from_u32(pua).map(String::from)
}

/// Display glyph of a w:sym: the Unicode equivalent when the font is a known
/// symbol face, else the U+F0xx private-use form; `None` for a bad char.
pub fn symbol_glyph(font: &str, char_hex: &str) -> Option<String> {
    let code = parse_int(char_hex, Radix::Sixteen);
    if !code.is_finite() {
        return None;
    }
    decode_symbol_char(font, code)
        .map(str::to_owned)
        .or_else(|| symbol_pua_char(char_hex))
}

/// Raw-byte glyph codes to their U+F0xx private-use form.
pub fn to_symbol_pua(text: &str) -> String {
    text.chars()
        .map(|ch| {
            let code = u32::from(ch);
            if code > 0x20 && code <= 0xff {
                char::from_u32(0xf000 + code).unwrap_or(ch)
            } else {
                ch
            }
        })
        .collect()
}

/// Whole-string decode; `None` unless every non-whitespace char maps.
/// `text_glyphs_only` also refuses pictograph stand-ins and ASCII
/// approximations, so a text run only drops its font for glyphs a text font
/// draws faithfully.
pub fn decode_symbol_text(font: &str, text: &str, text_glyphs_only: bool) -> Option<String> {
    if !is_symbol_font(Some(font)) {
        return None;
    }
    let mut out = String::new();
    for ch in text.chars() {
        let code = u32::from(ch);
        if code <= 0x20 || code == 0xa0 {
            out.push(ch);
            continue;
        }
        let mapped = decode_symbol_char(font, f64::from(code))?;
        if text_glyphs_only {
            let first = mapped.chars().next().map(u32::from);
            let ascii = first.is_some_and(|first| first < 0x80);
            let text_glyph =
                js_regex!(r"^[^\p{Emoji_Presentation}\u{10000}-\u{10FFFF}]$", "u").test(mapped);
            if !text_glyph || (ascii && Some(code & 0xff) != single(mapped)) {
                return None;
            }
        }
        out.push_str(mapped);
    }
    Some(out)
}

/// The code point of a one-character string, as `mapped !== String.fromCharCode(c)` compares.
fn single(text: &str) -> Option<u32> {
    let mut chars = text.chars();
    match (chars.next(), chars.next()) {
        (Some(only), None) => Some(u32::from(only)),
        _ => None,
    }
}
