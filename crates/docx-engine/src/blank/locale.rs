//! `new Intl.Locale(tag).maximize().region` for the one question `blank.ts`
//! asks of it: is the region one where Word starts on Letter.
//!
//! JavaScript answers from the host's ICU. The tables below are a snapshot of
//! Node 22.22.3 (ICU 78.3, CLDR 48), taken by asking `Intl.Locale` about every
//! two- and three-letter language, every language with every script it has
//! likely subtags for, and every region code, and keeping only the answers
//! that are Letter regions (`tools/docx-diff/blank-locale-table.mjs` checks
//! and rewrites them). Another ICU (a browser, another Node) may answer
//! differently for a rare tag.
//!
//! The syntax check is the one `Intl.Locale` applies (a Unicode BCP 47 locale
//! identifier), with the ICU quirks it shows: a grandfathered tag is replaced
//! before variants are checked for repeats, a repeated `-u-` key relaxes the
//! keys after it, and a transformed language left with the single variant
//! `posix` is refused.

/// The region `new Intl.Locale(tag).maximize()` gives, where it is one of the
/// Letter regions; `None` for any other region, for none, and where
/// `Intl.Locale` throws.
pub(super) fn letter_region(tag: &str) -> Option<&'static str> {
    let tag = parse(tag)?;
    let mut language = tag.language.as_str();
    let mut region = tag.region.map(|region| region.to_ascii_uppercase());
    if region.is_none() && tag.variants.iter().any(|variant| variant == "aaland") {
        // und_aaland is und_AX
        region = Some("AX".to_owned());
    }
    if matches!(region.as_deref(), Some("ZZ" | "999")) {
        // an unknown region is filled in, unless language and script are both
        // given: then the tag is taken as maximal
        if language != "und" && tag.script.is_some() {
            return None;
        }
        region = None;
    }
    if let Some(code) = region {
        let letter = lookup2(&REGIONS, &code)?;
        // sgn_US, sgn_CO and sgn_MX are aliases that take the region away
        let signed = match (language, letter) {
            ("sgn", "US") => "ase",
            ("sgn", "CO") => "csn",
            ("sgn", "MX") => "mfs",
            _ => return Some(letter),
        };
        // ICU applies them before und_aaland gives the emptied region AX; a
        // numeric region is still there when und_aaland is applied
        let alphabetic = code.bytes().all(|byte| byte.is_ascii_alphabetic());
        if alphabetic && tag.variants.iter().any(|variant| variant == "aaland") {
            return None;
        }
        language = signed;
    }
    if let Some(script) = tag.script.as_deref()
        && let Some((_, _, region)) = SCRIPT_REGIONS
            .iter()
            .find(|(lang, scr, _)| *lang == language && *scr == script)
    {
        return *region;
    }
    lookup2(&LANGUAGE_REGIONS, language)
}

fn lookup2(table: &[(&str, &'static str)], key: &str) -> Option<&'static str> {
    table
        .iter()
        .find(|(listed, _)| *listed == key)
        .map(|(_, region)| *region)
}

/// The parts of a tag `Intl.Locale` accepts, lowercased.
struct Tag {
    language: String,
    script: Option<String>,
    region: Option<String>,
    variants: Vec<String>,
}

fn alpha(s: &str, min: usize, max: usize) -> bool {
    (min..=max).contains(&s.len()) && s.bytes().all(|b| b.is_ascii_lowercase())
}

fn digits(s: &str, len: usize) -> bool {
    s.len() == len && s.bytes().all(|b| b.is_ascii_digit())
}

fn alnum(s: &str, min: usize, max: usize) -> bool {
    (min..=max).contains(&s.len())
        && s.bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit())
}

fn is_language(s: &str) -> bool {
    alpha(s, 2, 3) || alpha(s, 5, 8)
}

fn is_region(s: &str) -> bool {
    alpha(s, 2, 2) || digits(s, 3)
}

fn is_variant(s: &str) -> bool {
    alnum(s, 5, 8) || (alnum(s, 4, 4) && s.bytes().next().is_some_and(|b| b.is_ascii_digit()))
}

/// The variants CLDR's und_* aliases remove from any language.
const DROPPED_VARIANTS: [&str; 9] = [
    "aaland", "arevela", "arevmda", "bokmal", "hakka", "lojban", "nynorsk", "saaho", "xiang",
];

/// The grandfathered tags that are replaced whole before variants are checked.
const GRANDFATHERED: [(&str, &str); 4] = [
    ("art", "lojban"),
    ("zh", "guoyu"),
    ("zh", "hakka"),
    ("zh", "xiang"),
];

fn parse(tag: &str) -> Option<Tag> {
    let subtags: Vec<String> = tag.split('-').map(str::to_ascii_lowercase).collect();
    let well_formed =
        |s: &String| (1..=8).contains(&s.len()) && s.bytes().all(|b| b.is_ascii_alphanumeric());
    if !subtags.iter().all(well_formed) {
        return None;
    }
    let at = |i: usize| subtags.get(i).map_or("", String::as_str);
    let count = subtags.len();
    let language = at(0).to_owned();
    if !is_language(&language) {
        return None;
    }
    let mut i = 1;
    let mut script = None;
    let mut region = None;
    if i < count && alpha(at(i), 4, 4) {
        script = Some(at(i).to_owned());
        i += 1;
    }
    if i < count && is_region(at(i)) {
        region = Some(at(i).to_owned());
        i += 1;
    }
    if i == 1 && i < count && GRANDFATHERED.contains(&(language.as_str(), at(i))) {
        i += 1;
    }
    let mut variants: Vec<String> = Vec::new();
    while i < count && is_variant(at(i)) {
        if variants.iter().any(|seen| seen == at(i)) {
            return None;
        }
        variants.push(at(i).to_owned());
        i += 1;
    }
    let mut singletons: Vec<&str> = Vec::new();
    while i < count {
        let singleton = at(i);
        if singleton.len() != 1 || singletons.contains(&singleton) {
            return None;
        }
        singletons.push(singleton);
        i += 1;
        let start = i;
        match singleton {
            "x" => {
                while i < count && alnum(at(i), 1, 8) {
                    i += 1;
                }
                if i == start || i != count {
                    return None;
                }
            }
            "u" => {
                while i < count && alnum(at(i), 3, 8) {
                    i += 1;
                }
                // ICU drops a repeated key, and from then on drops instead of
                // refusing any two-character key
                let mut keys: Vec<&str> = Vec::new();
                let mut repeated = false;
                while i < count && is_u_key(at(i), repeated) {
                    repeated |= keys.contains(&at(i));
                    keys.push(at(i));
                    i += 1;
                    while i < count && alnum(at(i), 3, 8) {
                        i += 1;
                    }
                }
                if i == start {
                    return None;
                }
            }
            "t" => {
                if i < count && is_language(at(i)) {
                    i += 1;
                    if i < count && alpha(at(i), 4, 4) {
                        i += 1;
                    }
                    if i < count && is_region(at(i)) {
                        i += 1;
                    }
                    let mut tlang_variants: Vec<&str> = Vec::new();
                    while i < count && is_variant(at(i)) {
                        if tlang_variants.contains(&at(i)) {
                            return None;
                        }
                        tlang_variants.push(at(i));
                        i += 1;
                    }
                    // ICU moves a lone posix variant to u-va-posix, which a
                    // transformed language cannot hold
                    let mut kept = tlang_variants
                        .iter()
                        .filter(|variant| !DROPPED_VARIANTS.contains(*variant));
                    if kept.next() == Some(&"posix") && kept.next().is_none() {
                        return None;
                    }
                }
                while i < count && is_t_key(at(i)) {
                    i += 1;
                    let values = i;
                    while i < count && alnum(at(i), 3, 8) {
                        i += 1;
                    }
                    if i == values {
                        return None;
                    }
                }
                if i == start {
                    return None;
                }
            }
            _ => {
                while i < count && alnum(at(i), 2, 8) {
                    i += 1;
                }
                if i == start {
                    return None;
                }
            }
        }
    }
    Some(Tag {
        language,
        script,
        region,
        variants,
    })
}

/// `alphanum alpha`; any two characters once a key was repeated.
fn is_u_key(s: &str, repeated: bool) -> bool {
    alnum(s, 2, 2) && (repeated || s.as_bytes().get(1).is_some_and(u8::is_ascii_lowercase))
}

/// `alpha digit`
fn is_t_key(s: &str) -> bool {
    let mut bytes = s.bytes();
    s.len() == 2
        && bytes.next().is_some_and(|b| b.is_ascii_lowercase())
        && bytes.next().is_some_and(|b| b.is_ascii_digit())
}

